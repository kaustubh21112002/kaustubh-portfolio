/**
 * AI Provider Abstraction Interface & Safe Local Mock Provider
 * 
 * Safety Mandate:
 * - Local/Disabled provider by default.
 * - Zero external provider calls.
 * - Zero API credentials required.
 * - Zero environment variable dependencies.
 * - Zero network transmission of candidate data.
 * - Suggestions emitted by AI must be labeled AI_SUGGESTION and can NEVER
 *   be automatically converted into CONFIRMED claims.
 */

import type { CandidateClaim } from '../types/candidate.js';

export interface AISuggestionDraft {
  suggestionId: string;
  claimKey: string;
  suggestedValue: unknown;
  rationale: string;
  confidence: number; // 0.0 - 1.0
  createdAt: string;
}

export interface IAICareerProvider {
  readonly providerName: string;
  readonly isConnected: boolean;
  readonly modelId?: string;

  /**
   * Generates draft tailoring suggestions or skill interpretations.
   * Outputs are strictly suggestions and require explicit candidate confirmation.
   */
  generateSuggestions(params: {
    contextClaimKeys: string[];
    task: 'TAILOR_SUMMARY' | 'EXTRACT_IMPLICIT_SKILLS' | 'MAP_PROJECT_CONTRIBUTION';
    promptContext: Record<string, unknown>;
  }): Promise<AISuggestionDraft[]>;
}

/**
 * Disabled / Safe Local Mock Provider
 * Ensures local development, testing, and CI can run without network access or credentials.
 */
export class SafeLocalMockAIProvider implements IAICareerProvider {
  public readonly providerName = 'SafeLocalMockAIProvider';
  public readonly isConnected = false; // Always false in mock mode
  public readonly modelId = 'local-offline-mock';

  async generateSuggestions(params: {
    contextClaimKeys: string[];
    task: 'TAILOR_SUMMARY' | 'EXTRACT_IMPLICIT_SKILLS' | 'MAP_PROJECT_CONTRIBUTION';
    promptContext: Record<string, unknown>;
  }): Promise<AISuggestionDraft[]> {
    const now = new Date().toISOString();

    // Deterministic offline mock outputs for testing
    if (params.task === 'TAILOR_SUMMARY') {
      return [
        {
          suggestionId: 'sugg_mock_summary_1',
          claimKey: 'summary.overview',
          suggestedValue: 'Results-driven Analytics Engineer specializing in financial DCF modeling and decision intelligence.',
          rationale: 'Synthesized from core competencies without adding external claims.',
          confidence: 0.88,
          createdAt: now
        }
      ];
    }

    if (params.task === 'EXTRACT_IMPLICIT_SKILLS') {
      return [
        {
          suggestionId: 'sugg_mock_skill_1',
          claimKey: 'skill.cash_flow_forecasting',
          suggestedValue: {
            name: 'Cash Flow Forecasting',
            category: 'FINANCIAL_MODELING',
            proficiency: 'PROFICIENT'
          },
          rationale: 'Inferred from explicit FCFF forecasting in PhonePe valuation model.',
          confidence: 0.92,
          createdAt: now
        }
      ];
    }

    return [];
  }
}

/**
 * Utility to transform an AI suggestion into a CandidateClaim in AI_SUGGESTION status.
 * Note: Must be reviewed and explicitly confirmed by the candidate before use.
 */
export function createClaimFromAISuggestion(
  suggestion: AISuggestionDraft,
  claimType: CandidateClaim['claimType'],
  providerName: string
): CandidateClaim {
  return {
    claimId: `claim_${suggestion.suggestionId}`,
    claimType,
    claimKey: suggestion.claimKey,
    claimValue: suggestion.suggestedValue,
    sourceDocument: `AI_PROVIDER:${providerName}`,
    sourceSection: 'AI Suggestion Engine',
    sourceTextSnippet: suggestion.rationale,
    evidenceReference: {
      type: 'DOCUMENT_ASSERTION',
      notes: `Generated by ${providerName} with confidence ${suggestion.confidence}. Requires explicit candidate confirmation.`
    },
    extractionMethod: 'AI_ASSISTED_DRAFT',
    verificationStatus: 'AI_SUGGESTION',
    lastModifiedAt: suggestion.createdAt,
    permittedUse: 'INTERNAL_MATCHING_ONLY' // Forbidden in live resume until confirmed
  };
}

